CREATE OR REPLACE PACKAGE BODY PKG_AGENDA_HEMODIALISE AS

    C_NM_USUARIO_SISTEMA      CONSTANT VARCHAR2(30) := 'AUTOMACAO_HEMO';

    -- Procedure interna para gravar logs
    PROCEDURE PRC_GRAVA_LOG (p_procedure IN VARCHAR2, p_tipo IN VARCHAR2, p_paciente IN NUMBER, p_mensagem IN VARCHAR2) AS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        INSERT INTO LOG_AUTOMACAO_HEMO (ID_LOG, NM_PROCEDURE, TP_MENSAGEM, CD_PACIENTE, DS_MENSAGEM)
        VALUES (SEQ_LOG_AUTOMACAO_HEMO.NEXTVAL, p_procedure, p_tipo, p_paciente, p_mensagem);
        COMMIT;
    EXCEPTION WHEN OTHERS THEN NULL;
    END PRC_GRAVA_LOG;

    -- <<== PROCEDURE ATUALIZADA COM LÓGICA CORRIGIDA E AUTÔNOMA ==>>
    PROCEDURE PRC_INICIA_AGENDA_PAC_NOVO (
        P_CD_PACIENTE IN PACIENTE.CD_PACIENTE%TYPE
    ) AS
        V_DATA_HOJE                 DATE := SYSDATE;
        V_CD_ATENDIMENTO_PAI_FINAL  NUMBER;
        V_MENSAGEM_STATUS           VARCHAR2(2000);
        V_DT_INICIO_GERACAO         DATE;
        V_DT_FIM_GERACAO            DATE;
        V_PACIENTE_CONFIG           PACIENTE_TURMA_HEMO%ROWTYPE;
        V_DT_PRIMEIRO_DIA_MES_ATUAL DATE := TRUNC(V_DATA_HOJE, 'MM');
    BEGIN
        PRC_GRAVA_LOG('PRC_INICIA_AGENDA_PAC_NOVO', 'INFO', P_CD_PACIENTE, '--- INICIOU PROCESSO ON-DEMAND ---');
        SAVEPOINT INICIO_PACIENTE_NOVO;
        PKG_MV2000.ATRIBUI_EMPRESA(1);

        -- 1. Busca as configurações do paciente, validando para a data de HOJE
        BEGIN
            SELECT * INTO V_PACIENTE_CONFIG FROM PACIENTE_TURMA_HEMO
            WHERE CD_PACIENTE = P_CD_PACIENTE AND SN_ATIVO = 'S'
            AND V_DATA_HOJE BETWEEN DT_INICIO_VIGENCIA AND NVL(DT_FIM_VIGENCIA, V_DATA_HOJE)
            ORDER BY DT_INICIO_VIGENCIA DESC FETCH FIRST 1 ROW ONLY;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            V_MENSAGEM_STATUS := 'Paciente ' || P_CD_PACIENTE || ' nao encontrado ou inativo na PACIENTE_TURMA_HEMO para a data de hoje.';
            PRC_GRAVA_LOG('PRC_INICIA_AGENDA_PAC_NOVO', 'ERRO', P_CD_PACIENTE, V_MENSAGEM_STATUS);
            RETURN;
        END;

        -- 2. Cria o atendimento-pai para o MÊS CORRENTE
        BEGIN
            SELECT CD_ATENDIMENTO INTO V_CD_ATENDIMENTO_PAI_FINAL FROM ATENDIME
            WHERE CD_PACIENTE = P_CD_PACIENTE AND TRUNC(DT_ATENDIMENTO, 'MM') = V_DT_PRIMEIRO_DIA_MES_ATUAL AND TP_ATENDIMENTO = 'A';
            V_MENSAGEM_STATUS := 'JA EXISTE: Atendimento-pai ' || V_CD_ATENDIMENTO_PAI_FINAL || ' ja existe para este paciente/mes.';
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                INSERT INTO ATENDIME (CD_ATENDIMENTO, CD_ORI_ATE, CD_PACIENTE, CD_CONVENIO, CD_CON_PLA, CD_SUB_PLANO, DT_ATENDIMENTO, HR_ATENDIMENTO, TP_ATENDIMENTO, CD_MULTI_EMPRESA, SN_IMPORTA_AUTO, SN_BUSCA_ATIVA, SN_EM_ATENDIMENTO, TP_PRIORIDADE, SN_RECEBE_VISITA, SN_RELACAO_TRABALHO, SN_SUSPEITA_EPIDEMIA, SN_INTERNADO, NM_USUARIO, CD_SER_DIS, CD_TIPO_INTERNACAO, CD_PRESTADOR, CD_ESPECIALID, CD_CID, CD_CBO_PRESTADOR, CD_LOC_PROCED, SN_ATENDIMENTO_APAC, CD_PROCEDIMENTO, SN_RETORNO, CD_TIP_MAR, SN_CONSULTA_SIASUS, CD_CARATER_ATENDIMENTO, CD_PRO_INT)
                VALUES (SEQ_ATENDIME.NEXTVAL, V_PACIENTE_CONFIG.CD_ORI_ATE, P_CD_PACIENTE, V_PACIENTE_CONFIG.CD_CONVENIO, V_PACIENTE_CONFIG.CD_CON_PLAN, V_PACIENTE_CONFIG.CD_SUB_PLANO, TRUNC(V_DATA_HOJE), V_DATA_HOJE, 'A', 1, 'N', 'N', 'N', 'B', 'S', 'N', 'N', 'N', C_NM_USUARIO_SISTEMA, V_PACIENTE_CONFIG.CD_SER_DIS, V_PACIENTE_CONFIG.CD_TIPO_INTERNACAO, V_PACIENTE_CONFIG.CD_PRESTADOR, V_PACIENTE_CONFIG.CD_ESPECIALID, V_PACIENTE_CONFIG.CD_CID, V_PACIENTE_CONFIG.CD_CBO_PRESTADOR, V_PACIENTE_CONFIG.CD_LOC_PROCED, V_PACIENTE_CONFIG.SN_ATENDIMENTO_APAC, V_PACIENTE_CONFIG.CD_PROCEDIMENTO_SUS, 'N', V_PACIENTE_CONFIG.CD_TIP_MAR, 'S', 1, V_PACIENTE_CONFIG.CD_PROCEDIMENTO)
                RETURNING CD_ATENDIMENTO INTO V_CD_ATENDIMENTO_PAI_FINAL;
                V_MENSAGEM_STATUS := 'SUCESSO: Atendimento-pai ' || V_CD_ATENDIMENTO_PAI_FINAL || ' criado para ' || TO_CHAR(V_DT_PRIMEIRO_DIA_MES_ATUAL, 'MM/YYYY');
        END;
        PRC_GRAVA_LOG('PRC_INICIA_AGENDA_PAC_NOVO', 'INFO', P_CD_PACIENTE, 'Status Atendimento-Pai: ' || V_MENSAGEM_STATUS);

        -- 3. Gera as sessões para o RESTANTE do mês atual e cria filhos se necessário
        IF V_CD_ATENDIMENTO_PAI_FINAL IS NOT NULL THEN
            SELECT GREATEST(TRUNC(V_DATA_HOJE), TRUNC(DT_ATENDIMENTO)), LAST_DAY(V_DATA_HOJE)
            INTO   V_DT_INICIO_GERACAO, V_DT_FIM_GERACAO
            FROM   ATENDIME WHERE  CD_ATENDIMENTO = V_CD_ATENDIMENTO_PAI_FINAL;

            PRC_GERA_SESSOES_AGENDADAS(P_CD_ATENDIMENTO_PAI => V_CD_ATENDIMENTO_PAI_FINAL, P_DT_INICIO => V_DT_INICIO_GERACAO, P_DT_FIM => V_DT_FIM_GERACAO, P_DT_VALIDACAO => V_DATA_HOJE);
            PRC_GRAVA_LOG('PRC_INICIA_AGENDA_PAC_NOVO', 'INFO', P_CD_PACIENTE, 'Sessoes geradas/verificadas para o restante do mes.');

            -- <<== CORRIGIDO: Loop agora começa em 0 para incluir o dia de HOJE ==>>
            FOR i IN 0..5 LOOP
                PRC_CRIA_ATD_FILHO_SESSAO(P_DATA_ALVO_TESTE => TRUNC(V_DATA_HOJE) + i);
            END LOOP;
            PRC_GRAVA_LOG('PRC_INICIA_AGENDA_PAC_NOVO', 'INFO', P_CD_PACIENTE, 'Verificacao de atendimentos-filho para hoje e os proximos 5 dias concluida.');
        END IF;

        COMMIT;
        PRC_GRAVA_LOG('PRC_INICIA_AGENDA_PAC_NOVO', 'INFO', P_CD_PACIENTE, '--- PROCESSO ON-DEMAND FINALIZADO COM SUCESSO ---');
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO INICIO_PACIENTE_NOVO;
            PRC_GRAVA_LOG('PRC_INICIA_AGENDA_PAC_NOVO', 'ERRO', P_CD_PACIENTE, 'ERRO GRAVE NO PROCESSO ON-DEMAND: ' || SQLERRM);
    END PRC_INICIA_AGENDA_PAC_NOVO;


    PROCEDURE PRC_CRIA_ATENDIMENTO_PAI_MES (P_CD_PACIENTE IN PACIENTE.CD_PACIENTE%TYPE, P_DT_REFERENCIA IN DATE, P_CD_ATENDIMENTO_GERADO OUT ATENDIME.CD_ATENDIMENTO%TYPE, P_MENSAGEM_ERRO OUT VARCHAR2) AS
        V_CD_ATENDIMENTO_EXISTE   ATENDIME.CD_ATENDIMENTO%TYPE; V_PACIENTE_CONFIG PACIENTE_TURMA_HEMO%ROWTYPE; V_DT_PRIMEIRO_DIA_PROX_MES DATE := LAST_DAY(P_DT_REFERENCIA) + 1;
    BEGIN
        P_MENSAGEM_ERRO := NULL; PKG_MV2000.ATRIBUI_EMPRESA(1);
        BEGIN
            SELECT * INTO V_PACIENTE_CONFIG FROM PACIENTE_TURMA_HEMO WHERE CD_PACIENTE = P_CD_PACIENTE AND SN_ATIVO = 'S' AND P_DT_REFERENCIA BETWEEN DT_INICIO_VIGENCIA AND NVL(DT_FIM_VIGENCIA, P_DT_REFERENCIA) ORDER BY DT_INICIO_VIGENCIA DESC FETCH FIRST 1 ROW ONLY;
        EXCEPTION WHEN NO_DATA_FOUND THEN P_MENSAGEM_ERRO := 'Paciente ' || P_CD_PACIENTE || ' nao encontrado ou inativo na PACIENTE_TURMA_HEMO.'; RETURN; END;
        BEGIN
            SELECT CD_ATENDIMENTO INTO V_CD_ATENDIMENTO_EXISTE FROM ATENDIME WHERE CD_PACIENTE = P_CD_PACIENTE AND TRUNC(DT_ATENDIMENTO, 'MM') = TRUNC(V_DT_PRIMEIRO_DIA_PROX_MES, 'MM') AND TP_ATENDIMENTO = 'A';
            P_CD_ATENDIMENTO_GERADO := V_CD_ATENDIMENTO_EXISTE; P_MENSAGEM_ERRO := 'JA EXISTE: Atendimento-pai ' || V_CD_ATENDIMENTO_EXISTE || ' ja existe para este paciente/mes.'; RETURN;
        EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
        INSERT INTO ATENDIME (CD_ATENDIMENTO, CD_ORI_ATE, CD_PACIENTE, CD_CONVENIO, CD_CON_PLA, CD_SUB_PLANO, DT_ATENDIMENTO, HR_ATENDIMENTO, TP_ATENDIMENTO, CD_MULTI_EMPRESA, SN_IMPORTA_AUTO, SN_BUSCA_ATIVA, SN_EM_ATENDIMENTO, TP_PRIORIDADE, SN_RECEBE_VISITA, SN_RELACAO_TRABALHO, SN_SUSPEITA_EPIDEMIA, SN_INTERNADO, NM_USUARIO, CD_SER_DIS, CD_TIPO_INTERNACAO, CD_PRESTADOR, CD_ESPECIALID, CD_CID, CD_CBO_PRESTADOR, CD_LOC_PROCED, SN_ATENDIMENTO_APAC, CD_PROCEDIMENTO, SN_RETORNO, CD_TIP_MAR, SN_CONSULTA_SIASUS, CD_CARATER_ATENDIMENTO, CD_PRO_INT)
        VALUES (SEQ_ATENDIME.NEXTVAL, V_PACIENTE_CONFIG.CD_ORI_ATE, P_CD_PACIENTE, V_PACIENTE_CONFIG.CD_CONVENIO, V_PACIENTE_CONFIG.CD_CON_PLAN, V_PACIENTE_CONFIG.CD_SUB_PLANO, V_DT_PRIMEIRO_DIA_PROX_MES, V_DT_PRIMEIRO_DIA_PROX_MES, 'A', 1, 'N', 'N', 'N', 'B', 'S', 'N', 'N', 'N', C_NM_USUARIO_SISTEMA, V_PACIENTE_CONFIG.CD_SER_DIS, V_PACIENTE_CONFIG.CD_TIPO_INTERNACAO, V_PACIENTE_CONFIG.CD_PRESTADOR, V_PACIENTE_CONFIG.CD_ESPECIALID, V_PACIENTE_CONFIG.CD_CID, V_PACIENTE_CONFIG.CD_CBO_PRESTADOR, V_PACIENTE_CONFIG.CD_LOC_PROCED, V_PACIENTE_CONFIG.SN_ATENDIMENTO_APAC, V_PACIENTE_CONFIG.CD_PROCEDIMENTO_SUS, 'N', V_PACIENTE_CONFIG.CD_TIP_MAR, 'S', 1, V_PACIENTE_CONFIG.CD_PROCEDIMENTO)
        RETURNING CD_ATENDIMENTO INTO P_CD_ATENDIMENTO_GERADO;
    EXCEPTION WHEN OTHERS THEN P_CD_ATENDIMENTO_GERADO := NULL; P_MENSAGEM_ERRO := 'ERRO GERAL: ' || SQLERRM; RAISE;
    END PRC_CRIA_ATENDIMENTO_PAI_MES;

    PROCEDURE PRC_GERA_SESSOES_AGENDADAS (P_CD_ATENDIMENTO_PAI IN ATENDIME.CD_ATENDIMENTO%TYPE, P_DT_INICIO IN DATE, P_DT_FIM IN DATE, P_DT_VALIDACAO IN DATE) AS
       V_CD_PACIENTE PACIENTE.CD_PACIENTE%TYPE; V_PACIENTE_CONFIG PACIENTE_TURMA_HEMO%ROWTYPE; V_TURMA_INFO TURMA_HEMODIALISE%ROWTYPE; V_DATA_ATUAL DATE; V_DIA_SEMANA_ABREV VARCHAR2(3); V_SESSAO_JA_EXISTE NUMBER; V_SESSOES_CRIADAS_COUNT NUMBER := 0;
    BEGIN
        PKG_MV2000.ATRIBUI_EMPRESA(1);
        BEGIN
            SELECT CD_PACIENTE INTO V_CD_PACIENTE FROM ATENDIME WHERE CD_ATENDIMENTO = P_CD_ATENDIMENTO_PAI;
            SELECT * INTO V_PACIENTE_CONFIG FROM PACIENTE_TURMA_HEMO WHERE CD_PACIENTE = V_CD_PACIENTE AND SN_ATIVO = 'S' AND P_DT_VALIDACAO BETWEEN DT_INICIO_VIGENCIA AND NVL(DT_FIM_VIGENCIA, P_DT_VALIDACAO) ORDER BY DT_INICIO_VIGENCIA DESC FETCH FIRST 1 ROW ONLY;
            SELECT * INTO V_TURMA_INFO FROM TURMA_HEMODIALISE WHERE CD_TURMA = V_PACIENTE_CONFIG.CD_TURMA;
        EXCEPTION WHEN NO_DATA_FOUND THEN PRC_GRAVA_LOG('PRC_GERA_SESSOES_AGENDADAS', 'AVISO', V_CD_PACIENTE, 'Nao foi encontrada configuracao de turma. Sessoes nao geradas.'); RETURN; END;
        V_DATA_ATUAL := P_DT_INICIO;
        WHILE V_DATA_ATUAL <= P_DT_FIM LOOP
            V_DIA_SEMANA_ABREV := TO_CHAR(V_DATA_ATUAL, 'DY', 'NLS_DATE_LANGUAGE=PORTUGUESE');
            IF (V_TURMA_INFO.TP_DIAS_SEMANA = 'SQS' AND V_DIA_SEMANA_ABREV IN ('SEG', 'QUA', 'SEX')) OR (V_TURMA_INFO.TP_DIAS_SEMANA = 'TQS' AND V_DIA_SEMANA_ABREV IN ('TER', 'QUI', 'SÁB')) THEN
                SELECT COUNT(*) INTO V_SESSAO_JA_EXISTE FROM ATENDIME_SESSAO WHERE CD_ATENDIMENTO_PAI = P_CD_ATENDIMENTO_PAI AND TRUNC(DT_AGENDAMENTO) = TRUNC(V_DATA_ATUAL);
                IF V_SESSAO_JA_EXISTE = 0 THEN
                    DECLARE V_PODE_CRIAR BOOLEAN := TRUE;
                    BEGIN
                        IF TRUNC(V_DATA_ATUAL) = TRUNC(SYSDATE) THEN
                            IF V_TURMA_INFO.HR_ATENDIMENTO <= TO_CHAR(SYSDATE, 'HH24:MI') THEN
                                V_PODE_CRIAR := FALSE;
                                PRC_GRAVA_LOG('PRC_GERA_SESSOES_AGENDADAS', 'AVISO', V_CD_PACIENTE, 'Sessao para ' || TO_CHAR(V_DATA_ATUAL, 'DD/MM/YYYY') || ' ignorada pois o horario (' || V_TURMA_INFO.HR_ATENDIMENTO || ') ja passou.');
                            END IF;
                        END IF;
                        IF V_PODE_CRIAR THEN
                            INSERT INTO ATENDIME_SESSAO (CD_IT_ATENDIME_SESSAO, CD_ATENDIMENTO_PAI, CD_ATENDIMENTO, DT_AGENDAMENTO, HR_AGENDAMENTO, DT_ATENDIMENTO, HR_ATENDIMENTO, NM_USUARIO, SN_CANCELADO, CD_PROCEDIMENTO_SIA)
                            VALUES (SEQ_ATENDIME_SESSAO.NEXTVAL, P_CD_ATENDIMENTO_PAI, NULL, TRUNC(V_DATA_ATUAL), TO_DATE(TO_CHAR(V_DATA_ATUAL, 'DD/MM/YYYY') || ' ' || V_TURMA_INFO.HR_ATENDIMENTO, 'DD/MM/YYYY HH24:MI'), NULL, NULL, C_NM_USUARIO_SISTEMA, 'N', V_PACIENTE_CONFIG.CD_PROCEDIMENTO);
                            V_SESSOES_CRIADAS_COUNT := V_SESSOES_CRIADAS_COUNT + 1;
                        END IF;
                    END;
                END IF;
            END IF;
            V_DATA_ATUAL := V_DATA_ATUAL + 1;
        END LOOP;
        IF V_SESSOES_CRIADAS_COUNT > 0 THEN UPDATE ATENDIME SET QT_SESSOES = NVL(QT_SESSOES, 0) + V_SESSOES_CRIADAS_COUNT WHERE CD_ATENDIMENTO = P_CD_ATENDIMENTO_PAI; END IF;
    EXCEPTION WHEN OTHERS THEN RAISE; END PRC_GERA_SESSOES_AGENDADAS;

    PROCEDURE PRC_AUTOMATIZA_GERACAO_MENSAL AS
        V_DATA_HOJE DATE := SYSDATE; V_CD_ATENDIMENTO_PAI_FINAL NUMBER; V_MENSAGEM_STATUS VARCHAR2(2000); V_DT_INICIO_GERACAO DATE; V_DT_FIM_GERACAO DATE;
        V_TP_SITUACAO_PACIENTE PACIENTE.TP_SITUACAO%TYPE;

        CURSOR C_PACIENTES_ATIVOS IS
            SELECT pth.CD_PACIENTE FROM PACIENTE_TURMA_HEMO pth
            WHERE pth.SN_ATIVO = 'S' AND V_DATA_HOJE BETWEEN pth.DT_INICIO_VIGENCIA AND NVL(pth.DT_FIM_VIGENCIA, V_DATA_HOJE)
            GROUP BY pth.CD_PACIENTE;
    BEGIN
        PRC_GRAVA_LOG('PRC_AUTOMATIZA_GERACAO_MENSAL', 'INFO', NULL, '--- INICIO JOB MENSAL ---');
        FOR PAC IN C_PACIENTES_ATIVOS LOOP
            BEGIN
                SAVEPOINT INICIO_PACIENTE;
                SELECT TP_SITUACAO INTO V_TP_SITUACAO_PACIENTE FROM PACIENTE p WHERE p.CD_PACIENTE = PAC.CD_PACIENTE;
                IF V_TP_SITUACAO_PACIENTE = 'O' THEN
                    UPDATE PACIENTE_TURMA_HEMO SET SN_ATIVO = 'N', DT_FIM_VIGENCIA = TRUNC(SYSDATE)
                    WHERE CD_PACIENTE = PAC.CD_PACIENTE AND SN_ATIVO = 'S';
                    PRC_GRAVA_LOG('PRC_AUTOMATIZA_GERACAO_MENSAL', 'AVISO', PAC.CD_PACIENTE, 'Paciente com TP_SITUACAO = ''O'' (óbito). Desativado automaticamente da PACIENTE_TURMA_HEMO.');
                ELSE
                    PRC_CRIA_ATENDIMENTO_PAI_MES(P_CD_PACIENTE => PAC.CD_PACIENTE, P_DT_REFERENCIA => V_DATA_HOJE, P_CD_ATENDIMENTO_GERADO => V_CD_ATENDIMENTO_PAI_FINAL, P_MENSAGEM_ERRO => V_MENSAGEM_STATUS);
                    PRC_GRAVA_LOG('PRC_AUTOMATIZA_GERACAO_MENSAL', 'INFO', PAC.CD_PACIENTE, 'Status Atendimento-Pai: ' || V_MENSAGEM_STATUS);
                    IF V_CD_ATENDIMENTO_PAI_FINAL IS NOT NULL THEN
                        SELECT GREATEST(TRUNC(LAST_DAY(V_DATA_HOJE)+1, 'MM'), TRUNC(DT_ATENDIMENTO)) INTO V_DT_INICIO_GERACAO FROM ATENDIME WHERE CD_ATENDIMENTO = V_CD_ATENDIMENTO_PAI_FINAL;
                        V_DT_FIM_GERACAO := LAST_DAY(LAST_DAY(V_DATA_HOJE)+1);
                        PRC_GERA_SESSOES_AGENDADAS(P_CD_ATENDIMENTO_PAI => V_CD_ATENDIMENTO_PAI_FINAL, P_DT_INICIO => V_DT_INICIO_GERACAO, P_DT_FIM => V_DT_FIM_GERACAO, P_DT_VALIDACAO => V_DATA_HOJE);
                        PRC_GRAVA_LOG('PRC_AUTOMATIZA_GERACAO_MENSAL', 'INFO', PAC.CD_PACIENTE, 'Sessoes geradas/verificadas com sucesso para o atendimento ' || V_CD_ATENDIMENTO_PAI_FINAL);
                    END IF;
                END IF;
                COMMIT;
            EXCEPTION WHEN OTHERS THEN
                ROLLBACK TO INICIO_PACIENTE;
                PRC_GRAVA_LOG('PRC_AUTOMATIZA_GERACAO_MENSAL', 'ERRO', PAC.CD_PACIENTE, 'ERRO GRAVE: ' || SQLERRM);
            END;
        END LOOP;
        PRC_GRAVA_LOG('PRC_AUTOMATIZA_GERACAO_MENSAL', 'INFO', NULL, '--- FIM JOB MENSAL ---');
    END PRC_AUTOMATIZA_GERACAO_MENSAL;

    PROCEDURE PRC_CRIA_ATD_FILHO_SESSAO (P_DATA_ALVO_TESTE IN DATE DEFAULT NULL) AS
        V_DATA_ALVO DATE := NVL(P_DATA_ALVO_TESTE, TRUNC(SYSDATE) + 5);
        V_ATEND_PAI_REC ATENDIME%ROWTYPE;
        V_CD_ATENDIMENTO_FILHO ATENDIME.CD_ATENDIMENTO%TYPE;

        CURSOR C_SESSOES_A_PROCESSAR IS
            SELECT s.*, a.cd_paciente FROM ATENDIME_SESSAO s JOIN ATENDIME a ON s.CD_ATENDIMENTO_PAI = a.CD_ATENDIMENTO
            WHERE TRUNC(s.DT_AGENDAMENTO) = V_DATA_ALVO AND s.CD_ATENDIMENTO IS NULL AND s.SN_CANCELADO = 'N'
            AND TRUNC(s.DT_AGENDAMENTO) >= TRUNC(a.DT_ATENDIMENTO)
            AND EXISTS (SELECT 1 FROM PACIENTE_TURMA_HEMO pth
                        WHERE pth.CD_PACIENTE = a.CD_PACIENTE AND pth.SN_ATIVO = 'S'
                        AND V_DATA_ALVO BETWEEN pth.DT_INICIO_VIGENCIA AND NVL(pth.DT_FIM_VIGENCIA, V_DATA_ALVO));
    BEGIN
        PKG_MV2000.ATRIBUI_EMPRESA(1);
        PRC_GRAVA_LOG('PRC_CRIA_ATD_FILHO_SESSAO', 'INFO', NULL, '--- INICIO JOB DIARIO --- Buscando sessoes para: ' || TO_CHAR(V_DATA_ALVO, 'DD/MM/YYYY'));
        FOR SESSAO IN C_SESSOES_A_PROCESSAR LOOP
            BEGIN
                SAVEPOINT INICIO_SESSAO;
                SELECT * INTO V_ATEND_PAI_REC FROM ATENDIME WHERE CD_ATENDIMENTO = SESSAO.CD_ATENDIMENTO_PAI;
                INSERT INTO ATENDIME (CD_ATENDIMENTO, DT_ATENDIMENTO, HR_ATENDIMENTO, CD_ATENDIMENTO_PAI, CD_ORI_ATE, CD_PACIENTE, CD_CONVENIO, CD_CON_PLA, CD_SUB_PLANO, TP_ATENDIMENTO, CD_MULTI_EMPRESA, SN_IMPORTA_AUTO, SN_BUSCA_ATIVA, SN_EM_ATENDIMENTO, TP_PRIORIDADE, SN_RECEBE_VISITA, SN_RELACAO_TRABALHO, SN_SUSPEITA_EPIDEMIA, SN_INTERNADO, NM_USUARIO, CD_SER_DIS, CD_TIPO_INTERNACAO, CD_PRESTADOR, CD_ESPECIALID, CD_CID, CD_CBO_PRESTADOR, CD_LOC_PROCED, SN_ATENDIMENTO_APAC, CD_PROCEDIMENTO, SN_RETORNO, CD_TIP_MAR, SN_CONSULTA_SIASUS, CD_CARATER_ATENDIMENTO, CD_PRO_INT)
                VALUES (SEQ_ATENDIME.NEXTVAL, SESSAO.DT_AGENDAMENTO, SESSAO.HR_AGENDAMENTO, SESSAO.CD_ATENDIMENTO_PAI, V_ATEND_PAI_REC.CD_ORI_ATE, V_ATEND_PAI_REC.CD_PACIENTE, V_ATEND_PAI_REC.CD_CONVENIO, V_ATEND_PAI_REC.CD_CON_PLA, V_ATEND_PAI_REC.CD_SUB_PLANO, V_ATEND_PAI_REC.TP_ATENDIMENTO, V_ATEND_PAI_REC.CD_MULTI_EMPRESA, 'N', 'N', 'S', V_ATEND_PAI_REC.TP_PRIORIDADE, 'S', 'N', 'N', 'N', C_NM_USUARIO_SISTEMA, V_ATEND_PAI_REC.CD_SER_DIS, V_ATEND_PAI_REC.CD_TIPO_INTERNACAO, V_ATEND_PAI_REC.CD_PRESTADOR, V_ATEND_PAI_REC.CD_ESPECIALID, V_ATEND_PAI_REC.CD_CID, V_ATEND_PAI_REC.CD_CBO_PRESTADOR, V_ATEND_PAI_REC.CD_LOC_PROCED, V_ATEND_PAI_REC.SN_ATENDIMENTO_APAC, SESSAO.CD_PROCEDIMENTO_SIA, 'N', V_ATEND_PAI_REC.CD_TIP_MAR, 'S', V_ATEND_PAI_REC.CD_CARATER_ATENDIMENTO, SESSAO.CD_PROCEDIMENTO_SIA)
                RETURNING CD_ATENDIMENTO INTO V_CD_ATENDIMENTO_FILHO;
                UPDATE ATENDIME_SESSAO SET CD_ATENDIMENTO = V_CD_ATENDIMENTO_FILHO, DT_ATENDIMENTO = DT_AGENDAMENTO, HR_ATENDIMENTO = HR_AGENDAMENTO
                WHERE CD_IT_ATENDIME_SESSAO = SESSAO.CD_IT_ATENDIME_SESSAO;
                PRC_GRAVA_LOG('PRC_CRIA_ATD_FILHO_SESSAO', 'INFO', SESSAO.CD_PACIENTE, 'Sucesso! Atendimento-filho ' || V_CD_ATENDIMENTO_FILHO || ' criado para a sessao ' || SESSAO.CD_IT_ATENDIME_SESSAO);
                COMMIT;
            EXCEPTION
                WHEN OTHERS THEN
                    ROLLBACK TO INICIO_SESSAO;
                    PRC_GRAVA_LOG('PRC_CRIA_ATD_FILHO_SESSAO', 'ERRO', SESSAO.CD_PACIENTE, 'ERRO ao processar a sessao ' || SESSAO.CD_IT_ATENDIME_SESSAO || ': ' || SQLERRM);
